using Microsoft.AspNetCore.DataProtection.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using Server.Domain;

namespace Server.Infrastructure.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options)
    : DbContext(options), IDataProtectionKeyContext
{
    public DbSet<Presentation> Presentations => Set<Presentation>();
    public DbSet<Slide> Slides => Set<Slide>();
    public DbSet<SlideStep> SlideSteps => Set<SlideStep>();
    public DbSet<Widget> Widgets => Set<Widget>();
    public DbSet<Session> Sessions => Set<Session>();
    public DbSet<Participant> Participants => Set<Participant>();
    public DbSet<Attendance> Attendances => Set<Attendance>();
    public DbSet<WidgetLaunch> WidgetLaunches => Set<WidgetLaunch>();
    public DbSet<Response> Responses => Set<Response>();

    /// <summary>Keys that sign the auth cookies, so they survive container restarts.</summary>
    public DbSet<DataProtectionKey> DataProtectionKeys => Set<DataProtectionKey>();

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        configurationBuilder.Properties<Enum>().HaveConversion<string>().HaveMaxLength(32);
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Ids are Guid v7, generated by the entities themselves.
        modelBuilder.Entity<Presentation>(e =>
        {
            e.Property(p => p.Id).ValueGeneratedNever();
            e.Property(p => p.Title).HasMaxLength(200);
            e.Property(p => p.PptxPath).HasMaxLength(400);
            e.Property(p => p.PdfPath).HasMaxLength(400);
            e.Property(p => p.FailureReason).HasMaxLength(1000);
            e.HasMany(p => p.Slides).WithOne().HasForeignKey(s => s.PresentationId);
        });

        modelBuilder.Entity<Slide>(e =>
        {
            e.Property(s => s.Id).ValueGeneratedNever();
            e.HasIndex(s => new { s.PresentationId, s.Index }).IsUnique();
            e.HasMany(s => s.Steps).WithOne().HasForeignKey(st => st.SlideId);
            e.HasMany(s => s.Widgets).WithOne().HasForeignKey(w => w.SlideId);
        });

        modelBuilder.Entity<SlideStep>(e =>
        {
            e.Property(st => st.Id).ValueGeneratedNever();
            e.Property(st => st.ImagePath).HasMaxLength(400);
            e.HasIndex(st => new { st.SlideId, st.Index }).IsUnique();
        });

        modelBuilder.Entity<Widget>(e =>
        {
            e.Property(w => w.Id).ValueGeneratedNever();
        });

        modelBuilder.Entity<Session>(e =>
        {
            e.Property(s => s.Id).ValueGeneratedNever();
            e.Property(s => s.Code).HasMaxLength(8).IsFixedLength();
            e.HasOne<Presentation>().WithMany().HasForeignKey(s => s.PresentationId);
            // A code only needs to be unique while the session can still be joined.
            e.HasIndex(s => s.Code).IsUnique().HasFilter("[Status] <> 'Ended'");
        });

        modelBuilder.Entity<Participant>(e =>
        {
            e.Property(p => p.Id).ValueGeneratedNever();
            e.Property(p => p.Email).HasMaxLength(254);
            e.Property(p => p.Name).HasMaxLength(100);
            e.HasIndex(p => p.Email).IsUnique();
        });

        modelBuilder.Entity<Attendance>(e =>
        {
            e.Property(a => a.Id).ValueGeneratedNever();
            e.Property(a => a.DisplayName).HasMaxLength(100);
            e.Property(a => a.NoticeVersion).HasMaxLength(32);
            e.HasOne<Session>().WithMany().HasForeignKey(a => a.SessionId);
            // Restrict: a participant outlives any one session.
            e.HasOne<Participant>().WithMany().HasForeignKey(a => a.ParticipantId)
                .OnDelete(DeleteBehavior.Restrict);
            e.HasIndex(a => new { a.SessionId, a.ParticipantId }).IsUnique();
        });

        modelBuilder.Entity<WidgetLaunch>(e =>
        {
            e.Property(l => l.Id).ValueGeneratedNever();
            e.HasOne<Session>().WithMany().HasForeignKey(l => l.SessionId);
            // Restrict: SQL Server rejects a second cascade path from Presentation.
            e.HasOne<Widget>().WithMany().HasForeignKey(l => l.WidgetId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<Response>(e =>
        {
            e.Property(r => r.Id).ValueGeneratedNever();
            e.HasOne<WidgetLaunch>().WithMany().HasForeignKey(r => r.LaunchId);
            e.HasOne<Attendance>().WithMany().HasForeignKey(r => r.AttendanceId)
                .OnDelete(DeleteBehavior.Restrict);
            e.HasIndex(r => new { r.LaunchId, r.AttendanceId }).IsUnique();
        });
    }
}
